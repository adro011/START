/**
 * sync-content.mjs — compiles the human-editable content/*.txt files into
 * src/lib/content.generated.ts.
 *
 * The single source of truth is `content/` (plain `key = value` text files —
 * one per area of the site). This script reads them and emits a typed module
 * that the app imports. Edit the .txt files, then run `npm run content` (it
 * also runs automatically before `dev` and `build`).
 *
 * Format rules (per line):
 *   - Lines starting with "#" are comments (ignored).
 *   - Blank lines are ignored.
 *   - `key = value` sets a value. Keys may use dots to nest:
 *       faq.1.q = Question            -> { faq: [{ q: "Question" }] }
 *   - EXCEPTION: files under assets/, design/, motion/, scripts/ keep dotted
 *     keys literal (`hero.entryDuration` stays one flat token key).
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const CONTENT_DIR = join(ROOT, "content");
const OUT = join(ROOT, "src", "lib", "content.generated.ts");

/** Walks a directory, returning every *.txt file (recursive). */
function collectTxtFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      out.push(...collectTxtFiles(full));
    } else if (name.endsWith(".txt")) {
      out.push(full);
    }
  }
  return out;
}

/** Sets a dotted path on a target object (numeric segments stay as keys). */
function setPath(target, path, value) {
  const parts = path.split(".").filter(Boolean);
  let cursor = target;
  for (let i = 0; i < parts.length; i++) {
    const part = parts[i];
    const isLast = i === parts.length - 1;
    if (isLast) {
      cursor[part] = value;
    } else {
      if (cursor[part] === undefined || typeof cursor[part] !== "object") {
        cursor[part] = {};
      }
      cursor = cursor[part];
    }
  }
}

/**
 * Token folders keep dotted keys LITERAL (`hero.entryDuration` is one key),
 * because they are flat lookup tables read by asset()/designValue()/motionValue().
 * Copy files (home, pages, site) keep the nested behaviour (`hero.panel.1.title`).
 */
const FLAT_NAMESPACES = new Set(["assets", "design", "motion", "scripts"]);

/** Parses a single .txt file into an object. */
function parseFile(path, flat = false) {
  const text = readFileSync(path, "utf8");
  const result = {};
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    // Strip optional surrounding quotes.
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (!key) continue;
    if (flat) result[key] = value;
    else setPath(result, key, value);
  }
  return result;
}

function build() {
  if (!statSync(CONTENT_DIR, { throwIfNoEntry: false })) {
    throw new Error("content/ directory not found");
  }
  const files = collectTxtFiles(CONTENT_DIR);
  const compiled = {};

  for (const file of files) {
    const rel = relative(CONTENT_DIR, file).replace(/\\/g, "/").replace(/\.txt$/, "");
    const namespace = rel.split("/").filter(Boolean);
    const parsed = parseFile(file, FLAT_NAMESPACES.has(namespace[0]));
    let cursor = compiled;
    for (let i = 0; i < namespace.length; i++) {
      const part = namespace[i];
      const isLast = i === namespace.length - 1;
      if (isLast) {
        cursor[part] = parsed;
      } else {
        if (!cursor[part] || typeof cursor[part] !== "object") cursor[part] = {};
        cursor = cursor[part];
      }
    }
  }

  const banner = `// AUTO-GENERATED by scripts/sync-content.mjs — DO NOT EDIT BY HAND.\n// Source of truth: content/*.txt  (edit those, then run \`npm run content\`).\n\n`;
  const body = `export const GENERATED_CONTENT = ${JSON.stringify(compiled, null, 2)} as const;\n`;
  writeFileSync(OUT, banner + body, "utf8");
  console.log(`[sync-content] wrote ${relative(ROOT, OUT)} from ${files.length} file(s)`);
}

build();
